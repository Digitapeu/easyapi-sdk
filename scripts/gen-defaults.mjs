// Copies build-time package metadata into a module, because a JSON import cannot be written once
// in a form that both the ESM and the CJS build accept.
import { readFileSync, writeFileSync } from "node:fs";

const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
const baseUrl = pkg.easyapi?.defaultBaseUrl;
if (typeof baseUrl !== "string") throw new Error('package.json needs "easyapi.defaultBaseUrl"');

const source = `// Generated by scripts/gen-defaults.mjs from package.json; do not edit.
export const DEFAULT_BASE_URL = ${JSON.stringify(baseUrl)};
export const SDK_VERSION = ${JSON.stringify(pkg.version)};
`;
writeFileSync(new URL("../src/generated/metadata.ts", import.meta.url), source);
