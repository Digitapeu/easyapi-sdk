// Removes generator attribution from the built output that gets published.
// Runs on dist/ only; the source tree is untouched so regeneration stays clean.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const distDir = new URL("../dist", import.meta.url).pathname;
const headerBlock = /^\/\*(?:(?!\*\/)[\s\S])*Code generated by Speakeasy(?:(?!\*\/)[\s\S])*\*\/\n/;
const generatorUserAgent = /speakeasy-sdk\/typescript (\S+) \S+ \S+ \S+/g;

function* files(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) yield* files(path);
    else if (/\.(js|ts|map)$/.test(name)) yield path;
  }
}

const leftovers = [];
for (const path of files(distDir)) {
  const original = readFileSync(path, "utf8");
  const stripped = original
    .replace(headerBlock, "")
    .replace(generatorUserAgent, "easyapi-sdk-typescript/$1");
  if (stripped !== original) writeFileSync(path, stripped);
  if (/speakeasy/i.test(stripped)) leftovers.push(path);
}

if (leftovers.length > 0) {
  console.error(`generator wording remains in:\n${leftovers.join("\n")}`);
  process.exit(1);
}
